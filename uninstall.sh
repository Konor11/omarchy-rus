#!/usr/bin/env bash
# Полный откат omarchy-rus. Удаляет всё, что установил скрипт:
#   • клоны плагинов бара (возвращает оригиналы)
#   • расширение меню Omarchy
#   • обёртки меню горячих клавиш (Super+K, Tmux, Herdr) и патч bindings.lua
#   • хук post-update
#   • DNS-хелпер /usr/local/bin/omarchy-dns-ru (sudo)
#   • конфиг fastfetch (с бэкапом)
#   • сертификаты Минцифры и таймер (sudo, если ставились)
#   • установленные скрипты в ~/.local/share/omarchy-rus/
#
# По умолчанию НЕ трогает: локаль, раскладку клавиатуры, XCompose, шрифт TTY,
#   пакеты (hunspell-ru, telegram-desktop и т.д.), часовой пояс, voxtype, TTS.
#   Для полного сноса включая их: ./uninstall.sh --purge
#
#   ./uninstall.sh                полный откат артефактов перевода
#   ./uninstall.sh --dry-run      показать, что будет удалено, без действий
#   ./uninstall.sh --purge        удалить вообще всё (пакеты, локаль, сертификаты)
#   ./uninstall.sh --help         эта справка
set -uo pipefail

DRY=0
PURGE=0
USER=$(whoami)
PLUGINS_DIR="$HOME/.config/omarchy/plugins"
EXTENSIONS_DIR="$HOME/.config/omarchy/extensions"
HOOKS_DIR="$HOME/.config/omarchy/hooks/post-update.d"
LOCAL_BIN="$HOME/.local/bin"
LOCAL_SHARE="$HOME/.local/share/omarchy-rus"
BINDINGS="$HOME/.config/hypr/bindings.lua"
MARK_MENU="// Generated by omarchy-rus/translate-menu.py"
MARK_KB_BEGIN="-- >>> omarchy-rus: keybindings"
MARK_KB_END="-- <<< omarchy-rus: keybindings"
MARK_FF="// omarchy-rus: generated from"
DNS_HELPER="/usr/local/bin/omarchy-dns-ru"

# Все плагины, которые translate-plugins.py мог клонировать
CLONED_PLUGINS=(
  clock network bluetooth audio power monitor weather
  speedtest disk-speedtest tailscale notifications reminders
  clipboard emojis image-picker wifiqr dropbox agents
  indicators microphone system-update tray
)

# Пакеты, которые мог установить omarchy-rus (для --purge)
PURGE_PACKAGES=(
  hunspell-ru aspell-ru man-pages-ru
  telegram-desktop
  speech-dispatcher espeak-ng
  pcsclite ccid opensc pcsc-tools pcscd
)

usage() { sed -n '2,18p' "$0" | sed 's/^# \{0,1\}//'; }

say()  { printf '%s\n' "$*"; }
done_msg() { printf '  ✓ %s\n' "$*"; }
skip_msg() { printf '  · %s (не найдено)\n' "$*"; }

rm_safe() {
  if [ -e "$1" ] || [ -L "$1" ]; then
    if [ "$DRY" = 1 ]; then say "  [dry-run] rm $1"; else rm -rf -- "$1"; fi
    done_msg "удалён $1"
  else
    skip_msg "$1"
  fi
}

# --- 1. Клоны плагинов ---
remove_plugin_clones() {
  say "Клоны плагинов бара:"
  local removed=0
  for name in "${CLONED_PLUGINS[@]}"; do
    local clone="$PLUGINS_DIR/$USER.$name"
    local orig="omarchy.$name"
    if [ -d "$clone" ]; then
      if [ "$DRY" = 0 ]; then
        rm -rf -- "$clone"
        # Возвращаем оригинальный плагин
        omarchy plugin enable "$orig" 2>/dev/null || true
      fi
      done_msg "клон $USER.$name удалён, оригинал $orig включён"
      removed=$((removed + 1))
    fi
  done
  [ "$removed" = 0 ] && skip_msg "клоны плагинов не найдены"
}

# --- 2. Расширение меню ---
remove_menu_extension() {
  say "Расширение меню Omarchy:"
  local f="$EXTENSIONS_DIR/omarchy-menu.jsonc"
  if [ -f "$f" ] && grep -qF "$MARK_MENU" "$f" 2>/dev/null; then
    rm_safe "$f"
    done_msg "меню возвращено к оригиналу"
  else
    skip_msg "расширение меню (не omarchy-rus или отсутствует)"
  fi
}

# --- 3. Обёртки горячих клавиш и патч bindings.lua ---
remove_keybindings() {
  say "Меню горячих клавиш:"
  rm_safe "$LOCAL_BIN/omarchy-menu-keybindings-ru"
  rm_safe "$LOCAL_BIN/omarchy-menu-tmux-keybindings-ru"
  rm_safe "$LOCAL_BIN/omarchy-menu-herdr-keybindings-ru"

  # Патч bindings.lua: удаляем блок между маркерами
  if [ -f "$BINDINGS" ] && grep -qF "$MARK_KB_BEGIN" "$BINDINGS" 2>/dev/null; then
    if [ "$DRY" = 0 ]; then
      # Вырезаем блок от MARK_KB_BEGIN до MARK_KB_END включительно
      local tmp
      tmp=$(mktemp)
      awk -v b="$MARK_KB_BEGIN" -v e="$MARK_KB_END" '
        $0 == b { skip=1; next }
        $0 == e { skip=0; next }
        !skip { print }
      ' "$BINDINGS" > "$tmp" && mv "$tmp" "$BINDINGS"
      hyprctl reload 2>/dev/null || true
    fi
    done_msg "патч bindings.lua удалён (блок omarchy-rus: keybindings)"
  else
    skip_msg "патч bindings.lua"
  fi
}

# --- 4. Хук post-update ---
remove_post_update_hook() {
  say "Хук post-update:"
  rm_safe "$HOOKS_DIR/omarchy-rus.hook"
}

# --- 5. Установленные скрипты ---
remove_installed_scripts() {
  say "Установленные скрипты omarchy-rus:"
  rm_safe "$LOCAL_SHARE"
}

# --- 6. DNS-хелпер (sudo) ---
remove_dns_helper() {
  say "DNS-хелпер:"
  if [ -f "$DNS_HELPER" ]; then
    if [ "$DRY" = 0 ]; then
      sudo rm -f -- "$DNS_HELPER"
    fi
    done_msg "$DNS_HELPER удалён (sudo)"
  else
    skip_msg "$DNS_HELPER"
  fi
}

# --- 7. Конфиг fastfetch ---
remove_fastfetch() {
  say "Конфиг fastfetch:"
  local f="$HOME/.config/fastfetch/config.jsonc"
  if [ -f "$f" ] && grep -qF "$MARK_FF" "$f" 2>/dev/null; then
    # Ищем бэкап
    local backup
    backup=$(ls -t "$f.bak."* 2>/dev/null | head -1)
    if [ -n "$backup" ]; then
      if [ "$DRY" = 0 ]; then cp "$backup" "$f"; fi
      done_msg "конфиг восстановлен из $backup"
    else
      if [ "$DRY" = 0 ]; then rm -f -- "$f"; fi
      done_msg "конфиг удалён (бэкап не найден)"
    fi
  else
    skip_msg "конфиг fastfetch (не omarchy-rus или отсутствует)"
  fi
}

# --- 8. Сертификаты Минцифры (sudo, только --purge или если ставились) ---
remove_mincifry() {
  say "Сертификаты Минцифры:"
  local script="$LOCAL_SHARE/install-mincifry-ca.sh"
  local found=0

  # Проверяем, ставились ли сертификаты
  if ls /usr/share/ca-certificates/trust-source/anchors/mincifry* 1>/dev/null 2>&1 || \
     ls /etc/ca-certificates/trust-source/anchors/mincifry* 1>/dev/null 2>&1; then
    found=1
  fi

  if [ "$found" = 1 ] || [ "$PURGE" = 1 ]; then
    # Пытаемся использовать скрипт из репозитория, потом из установленной копии
    local mincifry_script
    mincifry_script="$(dirname "$(readlink -f "$0")")/install-mincifry-ca.sh"
    [ -x "$mincifry_script" ] || mincifry_script="$LOCAL_SHARE/install-mincifry-ca.sh"

    if [ -x "$mincifry_script" ]; then
      if [ "$DRY" = 0 ]; then
        sudo "$mincifry_script" --remove 2>/dev/null || true
        sudo "$mincifry_script" --disable-timer 2>/dev/null || true
      fi
      done_msg "сертификаты Минцифры удалены (sudo)"
    else
      skip_msg "скрипт install-mincifry-ca.sh не найден"
    fi
  else
    skip_msg "сертификаты Минцифры (не ставились)"
  fi
}

# --- 9. Перезапуск шелла ---
restart_shell() {
  if [ "$DRY" = 0 ]; then
    say "Перезапуск шелла Omarchy…"
    omarchy restart shell 2>/dev/null || true
  fi
}

# --- --purge: локаль, пакеты, раскладка ---
purge_system() {
  say "Полный снос (--purge):"

  # Пакеты
  say "  Удаление пакетов:"
  local pkg
  for pkg in "${PURGE_PACKAGES[@]}"; do
    if pacman -Q "$pkg" >/dev/null 2>&1; then
      if [ "$DRY" = 0 ]; then sudo pacman -Rs --noconfirm "$pkg" 2>/dev/null || true; fi
      done_msg "пакет $pkg удалён"
    else
      skip_msg "пакет $pkg"
    fi
  done

  # Локаль: возвращаем LANG=C
  local env_file="$HOME/.config/uwsm/env.d/50-omarchy-language"
  if [ -f "$env_file" ]; then
    rm_safe "$env_file"
    done_msg "LANG возвращён к умолчанию"
  fi

  # Раскладка: убираем us,ru из input.lua (оставляем только us)
  local input_lua="$HOME/.config/hypr/input.lua"
  if [ -f "$input_lua" ] && grep -q "us,ru" "$input_lua" 2>/dev/null; then
    if [ "$DRY" = 0 ]; then
      sed -i 's/us,ru/us/g' "$input_lua"
      hyprctl reload 2>/dev/null || true
    fi
    done_msg "раскладка возвращена на us"
  else
    skip_msg "раскладка (не us,ru или отсутствует)"
  fi

  # VConsole
  if [ -f "/etc/vconsole.conf" ] && grep -q "LatArCyrHeb" /etc/vconsole.conf 2>/dev/null; then
    if [ "$DRY" = 0 ]; then
      sudo sed -i 's/FONT=.*/FONT=/g' /etc/vconsole.conf
    fi
    done_msg "шрифт TTY сброшен"
  fi

  # XCompose
  # Не удаляем — пользователь мог сам писать туда. Только сообщаем.
  if [ -f "$HOME/.XCompose" ]; then
    say "  .XCompose: оставлен (проверьте вручную, если нужно)"
  fi

  # Язык Omarchy: сбрасываем на en
  local lang_file="$HOME/.config/omarchy/language"
  if [ -f "$lang_file" ]; then
    if [ "$DRY" = 0 ]; then
      echo "en" > "$lang_file"
    fi
    done_msg "язык Omarchy сброшен на en"
  fi
}

# --- Парсинг аргументов ---
while [ $# -gt 0 ]; do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --dry-run) DRY=1 ;;
    --purge) PURGE=1 ;;
    *) say "Неизвестный параметр: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

say "Откат omarchy-rus для пользователя: $USER"
[ "$DRY" = 1 ] && say "РЕЖИМ: dry-run (ничего не удаляется)"
say ""

remove_plugin_clones
echo
remove_menu_extension
echo
remove_keybindings
echo
remove_post_update_hook
echo
remove_installed_scripts
echo
remove_dns_helper
echo
remove_fastfetch
echo
remove_mincifry

if [ "$PURGE" = 1 ]; then
  echo
  purge_system
fi

echo
restart_shell

echo
say "Откат завершён."
say ""
say "Что осталось (по умолчанию не трогается):"
say "  • локаль ru_RU.UTF-8 и LANG"
say "  • раскладка us,ru"
say "  • XCompose (₽, №, «»)"
say "  • шрифт TTY"
say "  • пакеты (hunspell-ru, telegram-desktop, …)"
say "  • часовой пояс, voxtype, TTS"
say "  • язык Omarchy (~/.config/omarchy/language)"
say ""
say "Для полного сноса: ./uninstall.sh --purge"
say ""
say "Теперь можно установить свежую версию omarchy-rus или просто:"
say "  omarchy language ru"
